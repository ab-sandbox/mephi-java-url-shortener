CREATE TABLE users
(
    id         UUID PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE short_links
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      UUID                     NOT NULL,
    code         VARCHAR(32)              NOT NULL,
    original_url TEXT                     NOT NULL,
    click_limit  INTEGER                  NOT NULL,
    click_count  INTEGER                  NOT NULL DEFAULT 0,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_short_links_user
        FOREIGN KEY (user_id) REFERENCES users (id),

    CONSTRAINT uk_short_links_code
        UNIQUE (code),

    CONSTRAINT chk_short_links_click_limit
        CHECK (click_limit > 0),

    CONSTRAINT chk_short_links_click_count
        CHECK (click_count >= 0),

    CONSTRAINT chk_short_links_click_count_limit
        CHECK (click_count <= click_limit),

    CONSTRAINT chk_short_links_expiration
        CHECK (expires_at > created_at)
);

CREATE TABLE notifications
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    UUID                     NOT NULL,
    short_code VARCHAR(32)              NOT NULL,
    type       VARCHAR(32)              NOT NULL,
    message    TEXT                     NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at    TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_notifications_user
        FOREIGN KEY (user_id) REFERENCES users (id),

    CONSTRAINT chk_notifications_read_at
        CHECK (read_at IS NULL OR read_at >= created_at)
);

CREATE INDEX idx_short_links_user_id
    ON short_links (user_id);

CREATE INDEX idx_short_links_expires_at
    ON short_links (expires_at);

CREATE INDEX idx_notifications_user_id_created_at
    ON notifications (user_id, created_at DESC);
